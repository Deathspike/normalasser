export class Options {
  /**
   * Determines whether to check `.ass` files.
   *
   * @type {boolean | undefined}
   */
  checkAss;

  /**
   * Determines whether to force `.mkv` files.
   *
   * @type {boolean | undefined}
   */
  forceMkv;

  /**
   * The font size.
   *
   * @type {number | undefined}
   */
  size;
}
